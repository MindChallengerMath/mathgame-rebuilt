class Operations:
    def __init__(self):
        self.operators = ("+", "-", "*", "/")

    def plus(self, n1, n2):
        return n1 + n2
    
    def minus(self, n1, n2):
        return n1 - n2
    
    def multiply(self, n1, n2):
        return n1 * n2
    
    def divide(self, n1, n2):
        return n1 / n2

